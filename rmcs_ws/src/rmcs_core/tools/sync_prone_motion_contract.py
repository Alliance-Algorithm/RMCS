#!/usr/bin/env python3
"""Freeze the deployment subset of the current training-code contract, offline."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[4]


def number(value):
    value = struct.unpack("f", struct.pack("f", value))[0]
    text = f"{value:.9g}"
    return text + ("F" if "." in text or "e" in text else ".0F")


def vector(values):
    return "{" + ", ".join(map(number, values)) + "}"


def generate(training, revision=None):
    def read(path):
        if revision:
            return subprocess.check_output(["git", "show", revision+":"+str(path.relative_to(training))], cwd=training)
        return path.read_bytes()

    def source_digest(path):
        return hashlib.sha256(read(path)).hexdigest()

    plan_file = training / "contracts/wheel_leg_prone_motion_v4.json"
    plan = json.loads(read(plan_file))
    if plan["schema"] != "wheel-leg-prone-motion-v4":
        raise ValueError("Expected the latest prone-motion training-code v4 contract")
    observation = plan["standing_odometry"]
    obs_sha = hashlib.sha256(json.dumps(observation, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    if obs_sha != "6062baf37967d853446a95317aae4a0b315c4267da7387ab7ae020f37a021e35":
        raise ValueError("Observation contract changed; review the C++ preprocessor before syncing")
    table_file = training / observation["geometry_file"]
    if source_digest(table_file) != observation["geometry_table_sha256"]:
        raise ValueError("Standing geometry hash differs from training")
    table = json.loads(read(table_file))
    directory = table_file.parent
    spec_file = directory / "model_spec.json"
    spec_sha = source_digest(spec_file)
    if spec_sha != observation["geometry_model_spec_sha256"] or table["model_spec_sha256"] != spec_sha:
        raise ValueError("Full-vehicle geometry is bound to another model")
    manifest_file = directory / "manifest.json"
    manifest = json.loads(read(manifest_file))
    if manifest["files_sha256"]["model_spec.json"] != spec_sha:
        raise ValueError("Manifest model identity differs")
    recipe_file = training / plan["full_vehicle"]["file"]
    recipe = json.loads(read(recipe_file))
    if (source_digest(recipe_file) != plan["full_vehicle"]["sha256"]
            or recipe["asset_manifest_sha256"] != source_digest(manifest_file)
            or recipe["model_spec_sha256"] != spec_sha):
        raise ValueError("Full-vehicle recipe identity differs")
    gas_file = training / plan["gas_spring_feedforward"]["model_file"]
    gas = json.loads(read(gas_file))
    if (source_digest(gas_file) != plan["gas_spring_feedforward"]["model_sha256"]
            or gas["model_spec_sha256"] != spec_sha):
        raise ValueError("Gas-spring geometry identity differs")
    policy_order = ["L_joint1", "LL_joint1", "R_joint1", "RR_joint1", "L_joint3", "R_joint3"]
    nominal = [manifest["nominal_joint_pos"][name] for name in policy_order]
    if nominal[:4] != table["nominal_motor_positions"]:
        raise ValueError("Nominal legs differ between geometry and manifest")
    header = ["#pragma once", "", '#include "standing_reference_v3.hpp"', "",
              "// Generated by tools/sync_prone_motion_contract.py; float32 training knots.",
              "// Geometry JSON SHA256: " + source_digest(table_file),
              "namespace rmcs_core::controller::chassis::standing_reference {",
              "inline const GeometryTable& local_geometry107() {", "    static const GeometryTable table{{"]
    for side in ("left", "right"):
        row = table["sides"][side]
        header.append("        SideGeometry{" + vector(row["hip_origin_b_m"]) + ", "
                      + vector(row["hip_axis_b"]) + ", " + number(row["hip_reference_rad"]) + ", "
                      + number(row["wheel_radius_m"]) + ", {")
        for delta, center, beta in zip(row["delta_rad"], row["wheel_center_b_m"], row["passive_inner_deg"]):
            header.append("            GeometryKnot{" + number(delta) + ", " + vector(center) + ", " + number(beta) + "},")
        header.append("        }},")
    header.extend(["    }};", "    return table;", "}", "} // namespace rmcs_core::controller::chassis::standing_reference", ""])
    source_files = ["contracts/wheel_leg_prone_motion_v4.json", "contracts/wheel_leg_prone_motion_control_100hz_v1.json",
                    "contracts/standing_geometry107_v1.json", "src/wheeled_tasks/chassis/standing_local_odometry.py",
                    "src/wheeled_tasks/chassis/standing_sensor_uncertainty.py", "src/wheeled_algo/encoder_leg_geometry.py",
                    "src/wheeled_algo/standing_displacement.py", "src/wheeled_algo/rolling_velocity.py",
                    "src/wheeled_tasks/chassis/scut_observation.py", "src/wheeled_tasks/chassis/v5_control.py",
                    "scripts/train_prone_motion.py", "src/wheeled_algo/scratch_standing.py",
                    "src/wheeled_algo/paired_recovery.py",
                    "src/wheeled_tasks/chassis/paired_leg_targets.py",
                    "src/wheeled_tasks/chassis/full_vehicle_training.py",
                    "src/wheeled_tasks/chassis/gas_spring_compensation.py"]
    source_files += [str(path.relative_to(training)) for path in
        (table_file, spec_file, manifest_file, recipe_file, gas_file,
         directory / "gimbal_motion.json", directory / "wheel_model.json")]
    source_files += [plan[key]["file"] for key in ("mechanism", "pose_bank")]
    control_file = training / plan["wheel_model"]["control"]["file"]
    if source_digest(control_file) != plan["wheel_model"]["control"]["sha256"]:
        raise ValueError("Low-level control hash differs from the training plan")
    control = json.loads(read(control_file))
    contract = dict(schema="rmcs-prone-motion-deployment-code-v1", training_code_version=plan["schema"],
        training_commit=subprocess.check_output(["git", "rev-parse", revision or "HEAD"], cwd=training, text=True).strip(),
        source_sha256={name: source_digest(training / name) for name in source_files},
        observation=observation, observation_contract_sha256=obs_sha, timing=plan["timing"],
        model_spec_sha256=spec_sha, leg_winding_version="paired_branch107_v1",
        control_profile="full_vehicle_v202", nominal_policy_position=nominal,
        full_vehicle=dict(recipe=plan["full_vehicle"], asset_manifest_sha256=source_digest(manifest_file),
                          mass_kg=manifest["total_mass_kg"],
                          gimbal_mode=manifest["gimbal_mode"],
                          gimbal_policy_outputs=False),
        action_order=["left_hip_joint", "left_knee_joint", "right_hip_joint", "right_knee_joint", "left_wheel", "right_wheel"],
        action_scale=[.25] * 4 + [10.] * 2, raw_action_limit=[16.] * 4 + [9.] * 2,
        actuators=control["actuators"], gas_spring=plan["gas_spring_feedforward"],
        commands=dict(forward_m_s=plan["forward_speed_m_s"], yaw_rad_s=plan["spin_target_rpm"] * 6.283185307179586 / 60.,
                      height_m=[.23, .42]),
        normalization=dict(mode="embedded", metadata_key="rmcs_obs_normalization", frozen_training_statistics=True,
                           expression="RSL-RL eval normalizer before MLP; no second external standardization"),
        artifact_bound=False, behavior_qualified=False, hardware_tested=False)
    # Preserve the old chassis calibration for its existing configuration;
    # the full vehicle selects these independently authenticated tables.
    full = ["#pragma once", "", '#include "gas_spring_model.hpp"', "",
            "// Generated by tools/sync_prone_motion_contract.py from the full v2.0.2 vehicle.",
            "namespace rmcs_core::controller::chassis::full_vehicle_v202 {",
            f'inline constexpr std::string_view kModelSpecSha256 = "{spec_sha}";',
            f'inline constexpr std::string_view kObservationContractSha256 = "{obs_sha}";',
            f'inline constexpr std::string_view kGasModelSha256 = "{source_digest(gas_file)}";',
            "inline constexpr std::array<double, 6> kNominalPosition{" + ", ".join(map(repr, nominal)) + "};",
            "using GeometryKnot = gas_spring_model::GeometryKnot;",
            "using ForceKnot = gas_spring_model::ForceKnot;",
            f"inline constexpr std::array<ForceKnot, {len(gas['force_knots_n'])}> kForce{{{{"]
    full += ["    {" + f"{s:.17g}, {f:.17g}" + "}," for s, f in
             zip(gas["compression_knots_m"], gas["force_knots_n"])]
    full += ["}};",
             f"inline constexpr double kLowCompressionRate = {gas['force_extension']['low_compression_rate_per_m']:.17g};",
             f"inline constexpr double kHighCompressionSlope = {gas['force_extension']['high_compression_slope_n_per_m']:.17g};"]
    for side in ("left", "right"):
        row = gas["sides"][side]
        full.append(f"inline constexpr std::array<GeometryKnot, {len(row['delta_rad'])}> k{side.capitalize()}{{{{")
        for delta, beta, compression, jacobian in zip(row["delta_rad"], row["beta_deg"],
                row["compression_m"], row["length_jacobian_m_per_rad"]):
            full.append("    {" + ", ".join(f"{v:.17g}" for v in (delta, beta, compression, *jacobian)) + "},")
        full.append("}};")
    full += ["} // namespace rmcs_core::controller::chassis::full_vehicle_v202", ""]
    return {ROOT / "rmcs_ws/src/rmcs_core/src/controller/chassis/wheel_leg/standing_local_geometry.hpp": "\n".join(header),
            ROOT / "rmcs_ws/src/rmcs_core/src/controller/chassis/wheel_leg/full_vehicle_v202.hpp": "\n".join(full),
            ROOT / "rmcs_ws/src/rmcs_bringup/config/contracts/wheel_leg_prone_motion_v4.json": json.dumps(contract, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--training-root", type=Path, required=True)
    parser.add_argument("--training-revision", help="Read an exact committed training source without changing its checkout")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate(args.training_root.resolve(), args.training_revision).items():
        if args.check:
            if path.read_text() != content:
                raise ValueError("Frozen training contract differs: " + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        print(path.relative_to(ROOT))


if __name__ == "__main__":
    main()
