#!/usr/bin/env python3
"""Generate the jump deployment contract and geometry from a frozen training commit."""

import argparse
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
CONTRACT = ROOT / "rmcs_ws/src/rmcs_bringup/config/contracts/wheelbipe_jump_v4.json"
HEADER = (
    ROOT / "rmcs_ws/src/rmcs_core/src/controller/chassis/wheel_leg/model/jump_v4.hpp"
)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode()


def generate(repo, revision):
    commit = subprocess.check_output(
        ["git", "-C", str(repo), "rev-parse", revision + "^{commit}"], text=True
    ).strip()
    pins = {}

    def read(name):
        data = subprocess.check_output(
            ["git", "-C", str(repo), "show", commit + ":" + name]
        )
        pins[name] = digest(data)
        return json.loads(data)

    bundle = "model/wheel_leg_v2.0.2/friction_v1/isaac/"
    profile = read("contracts/wheelbipe_foundation_jump_v4.json")
    gas = read(bundle + "gas_spring_model.json")
    manifest = read(bundle + "manifest.json")
    read(bundle + "model_spec.json")
    read("model/gas_spring_identified_symmetric_20261028/model.json")
    control = {
        name: profile["control"][name]
        for name in (
            "leg_kp_nm_per_rad",
            "leg_kd_nm_s_per_rad",
            "virtual_pair_overtravel_rad",
            "virtual_pair_overtravel_scope",
            "tuck_spring_compensation",
        )
    }
    j = profile["jump"]
    bounds = [
        [gas["sides"][s]["delta_rad"][i] for i in (0, -1)] for s in ("left", "right")
    ]
    nominal = [
        manifest["nominal_joint_pos"][n]
        for n in (
            "L_joint1",
            "LL_joint1",
            "R_joint1",
            "RR_joint1",
            "L_joint3",
            "R_joint3",
        )
    ]
    request = {
        "standing_height_m": j["standing_height_m"],
        "crouch_height_m": j["crouch_height_m"],
        "release_height_m": j["release_height_m"],
        "crouch_seconds": j["crouch_seconds"],
        "apex_range_m": [j["apex_start_m"][0], j["apex_final_m"][1]],
        "nominal_request_delay_s": sum(j["request_delay_s"]) / 2,
        "outcome_seconds": j["outcome_seconds"],
        "moving_vx_max_m_s": j["moving_jump"]["maximum_vx_m_s"],
    }
    contract = {
        "schema": "wheelbipe-jump-v4-deployment-v1",
        "training_source_commit": commit,
        "training_profile": "foundation-jump-v4",
        "source_files_sha256": pins,
        "model_spec_sha256": pins[bundle + "model_spec.json"],
        "gas_model_sha256": pins[bundle + "gas_spring_model.json"],
        "policy_hz": profile["policy_hz"],
        "feedback_pd_hz": profile["physics_and_feedback_pd_hz"],
        "control": control,
        "request": request,
        "nominal_position": nominal,
        "winding_bounds_rad": bounds,
        "real_state_soft_limits_rad": gas["soft_limit_active_difference_rad"],
        "real_state_margin_rad": 0.03,
        "leg_torque_cap_nm": 40.0,
        "wheel_torque_cap_nm": 4.5,
        "observation_version": "wheelbipe-v202-foundation-jump-v4",
        "observation": {
            "size": 35,
            "action_size": 6,
            "normalization": "none",
            "joint_select": [0, 2, 1, 3, 4, 5],
            "order": [
                "command",
                "height",
                "gyro",
                "gravity",
                "position",
                "velocity",
                "previous_action",
                "auxiliary",
            ],
            "jump_context": "ordinary=[1,0,0,0,0,0,0]; request=[0,0,0,0,1,apex,elapsed_s]",
            "command_inputs": "external request and elapsed time only; no contact or measured apex",
        },
        "landing_buffer": {
            "seconds": j["landing_buffer_duration_s"],
            "scope": "training reward only; actor controls deployment landing",
        },
        "behavior_qualified": False,
        "hardware_tested": False,
    }
    contract["observation_contract_sha256"] = digest(
        canonical(
            {
                k: contract[k]
                for k in (
                    "model_spec_sha256",
                    "observation_version",
                    "observation",
                    "request",
                    "nominal_position",
                )
            }
        )
    )
    contract["deployment_contract_sha256"] = digest(canonical(contract))

    def number(value):
        return format(value, ".17g")

    lines = [
        "#pragma once",
        "",
        "#include <array>",
        "#include <string_view>",
        '#include "gas_spring_types.hpp"',
        "",
        "// Generated by tools/sync_wheelbipe_jump_contract.py from the pinned training commit.",
        "namespace rmcs_core::controller::chassis::wheelbipe_jump_v4 {",
    ]
    for key, value in (
        ("TrainingCommit", commit),
        ("ModelSpecSha256", contract["model_spec_sha256"]),
        ("GasModelSha256", contract["gas_model_sha256"]),
        ("ObservationSha256", contract["observation_contract_sha256"]),
        ("DeploymentSha256", contract["deployment_contract_sha256"]),
    ):
        lines.append(f'inline constexpr std::string_view k{key} = "{value}";')
    constants = {
        "LegKp": control["leg_kp_nm_per_rad"],
        "LegKd": control["leg_kd_nm_s_per_rad"],
        "Overtravel": control["virtual_pair_overtravel_rad"],
        "StandingHeight": request["standing_height_m"],
        "CrouchHeight": request["crouch_height_m"],
        "ReleaseHeight": request["release_height_m"],
        "CrouchSeconds": request["crouch_seconds"],
        "RequestDuration": request["outcome_seconds"]
        - request["nominal_request_delay_s"],
        "MinimumApex": request["apex_range_m"][0],
        "MaximumApex": request["apex_range_m"][1],
        "MovingVxMax": request["moving_vx_max_m_s"],
        "MechanicalMin": contract["real_state_soft_limits_rad"][0],
        "MechanicalMax": contract["real_state_soft_limits_rad"][1],
        "MechanicalMargin": 0.03,
        "LowCompressionRate": gas["force_extension"]["low_compression_rate_per_m"],
        "HighCompressionSlope": gas["force_extension"][
            "high_compression_slope_n_per_m"
        ],
    }
    settings = control["tuck_spring_compensation"]
    for field, name in (
        ("gain", "TuckGain"),
        ("cap_nm", "TuckCap"),
        ("error_on_rad", "ErrorOn"),
        ("error_full_rad", "ErrorFull"),
        ("inward_pd_full_nm", "InwardPdFull"),
    ):
        constants[name] = settings[field]
    for name, value in constants.items():
        lines.append(f"inline constexpr double k{name} = {number(value)};")
    lines.append(
        "inline constexpr std::array<std::array<double, 2>, 2> kBounds{{"
        + ",".join("{" + ",".join(map(number, row)) + "}" for row in bounds)
        + "}};"
    )
    lines.append(
        "inline constexpr std::array<gas_spring_model::ForceKnot, "
        + str(len(gas["compression_knots_m"]))
        + "> kForce{{"
    )
    for x, y in zip(gas["compression_knots_m"], gas["force_knots_n"]):
        lines.append("    {" + number(x) + "," + number(y) + "},")
    lines.append("}};")
    for side, name in (("left", "Left"), ("right", "Right")):
        row = gas["sides"][side]
        lines.append(
            f"inline constexpr std::array<gas_spring_model::GeometryKnot, {len(row['delta_rad'])}> k{name}"
            + "{{"
        )
        for delta, beta, compression, jac in zip(
            row["delta_rad"],
            row["beta_deg"],
            row["compression_m"],
            row["length_jacobian_m_per_rad"],
        ):
            lines.append(
                "    {" + ",".join(map(number, (delta, beta, compression, *jac))) + "},"
            )
        lines.append("}};")
    lines.append("} // namespace rmcs_core::controller::chassis::wheelbipe_jump_v4")
    return contract, "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--training-repo", type=Path, required=True)
    parser.add_argument("--revision", required=True)
    args = parser.parse_args()
    contract, header = generate(args.training_repo, args.revision)
    CONTRACT.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(header)
    CONTRACT.write_text(json.dumps(contract, indent=2) + "\n")
    print(contract["deployment_contract_sha256"])


if __name__ == "__main__":
    main()
