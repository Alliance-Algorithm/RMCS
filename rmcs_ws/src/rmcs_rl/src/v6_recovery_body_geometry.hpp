// The caller supplies finite, unit body-frame gravity. Positive depth is downward
// from the base origin, so wheel depth minus shell depth gives shell clearance.
[[nodiscard]] inline float support_depth(const Eigen::Vector3f& gravity) noexcept {
    float depth = std::numeric_limits<float>::lowest();
    for (const auto& vertex : kVertices)
        depth = std::max(depth, Eigen::Vector3f{vertex[0], vertex[1], vertex[2]}.dot(gravity));
    return depth;
}

